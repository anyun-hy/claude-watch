@main
struct EnvironmentDetailPresentationTests {
    static func main() {
        var count = 0
        func expect(_ value: @autoclosure () -> Bool, _ message: String) {
            count += 1
            precondition(value(), message)
        }
        var details = EnvironmentDetailPresentation()
        expect(!details.isPresented, "details start closed")
        details.hoverCard(true)
        expect(details.shouldPreview && !details.isPresented, "entering schedules a preview, not an immediate popup")
        details.hoverCard(false)
        details.previewIfNeeded()
        expect(!details.isPresented, "a delayed preview cannot open after the pointer has left")
        details.hoverCard(true)
        details.previewIfNeeded()
        expect(details.isPresented && !details.isPinned, "hover opens a temporary preview")
        details.hoverCard(false)
        expect(details.shouldClose, "leaving starts the close grace period")
        details.hoverDetails(true)
        details.closeIfNeeded()
        expect(details.isPresented, "moving into the popup keeps it readable and selectable")
        details.hoverDetails(false)
        details.closeIfNeeded()
        expect(!details.isPresented, "leaving both surfaces closes a temporary preview")
        details.activate()
        expect(details.isPresented && details.isPinned, "keyboard or click opens pinned details without hover")
        details.closeIfNeeded()
        expect(details.isPresented, "a pinned popup survives pointer departure")
        details.activate()
        expect(!details.isPresented && !details.isPinned, "activating a pinned card again closes it")
        details.hoverCard(true)
        details.previewIfNeeded()
        details.activate()
        expect(details.isPresented && details.isPinned, "clicking an existing hover preview pins it")
        details.dismiss()
        expect(!details.isPresented && !details.isPinned, "Escape or native outside dismissal clears the pin")
        details.previewIfNeeded()
        expect(!details.isPresented && !details.shouldPreview, "dismissal does not reopen under a stationary pointer")
        details.hoverCard(false)
        details.hoverCard(true)
        details.previewIfNeeded()
        expect(details.isPresented, "a new hover can reopen after dismissal")
        details.hoverDetails(true)
        details.togglePin()
        expect(details.isPinned, "the popup pin button keeps details open")
        details.hoverCard(false)
        details.hoverDetails(false)
        details.closeIfNeeded()
        expect(details.isPresented, "pinning defeats a pending pointer-close callback")
        details.hoverDetails(true)
        details.togglePin()
        details.closeIfNeeded()
        expect(details.isPresented && !details.isPinned, "unpinning while reading preserves the preview")
        details.hoverDetails(false)
        details.closeIfNeeded()
        expect(!details.isPresented, "unpinning returns to normal hover dismissal")
        print("Environment detail presentation: \(count) assertions passed")
    }
}
